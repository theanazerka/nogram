#!/usr/bin/env python3
"""Generate telegram/sources.mk (Theos file lists) from the original Xcode projects.

Everything that upstream builds as separate frameworks (LegacyComponents,
SSignalKit, Lottie, libtgvoip) is compiled statically into the app, because
iOS 6 cannot load embedded dynamic frameworks.

Run from the repository root: python3 tools/gen-telegram-mk.py
"""
import os
import subprocess
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'telegram')
PBX = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'pbx2files.py')

TARGETS = [
    ('TG_APP_FILES', 'Telegraph.xcodeproj', 'Telegraph', ''),
    ('TG_LEGACYCOMPONENTS_FILES', 'submodules/LegacyComponents/LegacyComponents.xcodeproj', 'LegacyComponents', 'submodules/LegacyComponents'),
    ('TG_SSIGNALKIT_FILES', 'thirdparty/SSignalKit/SSignalKit.xcodeproj', 'SSignalKit', 'thirdparty/SSignalKit'),
    ('TG_LOTTIE_FILES', 'thirdparty/Lottie/Lottie.xcodeproj', 'LottieLibraryIOS', 'thirdparty/Lottie'),
    ('TG_VOIP_FILES', 'submodules/libtgvoip/libtgvoip.xcodeproj', 'libtgvoip', 'submodules/libtgvoip'),
]

SOURCE_EXT = ('.m', '.mm', '.c', '.cpp', '.cc')


def make_escape(path):
    return path.replace(' ', '\\ ')


def main():
    out = ['# Generated by tools/gen-telegram-mk.py -- do not edit.', '']
    flags = []
    missing = []
    for var, proj, target, prefix in TARGETS:
        lines = subprocess.check_output([sys.executable, PBX, os.path.join(ROOT, proj), target], text=True).splitlines()
        files = []
        for line in lines:
            path, _, cflags = line.partition('\t')
            if not path.endswith(SOURCE_EXT) or path.startswith('$('):
                continue
            path = os.path.normpath(os.path.join(prefix, path))
            path = path.replace('thirdparty/Video Encoder', 'thirdparty/VideoEncoder')
            if not os.path.exists(os.path.join(ROOT, path)):
                missing.append(path)
                continue
            files.append(path)
            if cflags.strip():
                flags.append((path, cflags.strip()))
        out.append('%s = \\' % var)
        for f in sorted(set(files)):
            out.append('\t%s \\' % make_escape(f))
        out.append('')
    out.append('# Per-file flags from the Xcode projects.')
    for path, cflags in flags:
        out.append('%s_CFLAGS += %s' % (make_escape(path), cflags))
    out.append('')
    with open(os.path.join(ROOT, 'sources.mk'), 'w') as f:
        f.write('\n'.join(out))
    for m in missing:
        print('missing:', m, file=sys.stderr)
    print('sources.mk written, %d missing files' % len(missing))


if __name__ == '__main__':
    main()
